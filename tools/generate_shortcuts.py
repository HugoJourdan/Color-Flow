#!/usr/bin/env python3
"""Generate the 12 "Toggle <Color> Checkbox (Color Flow)" shortcut scripts.

Each emitted script is self-contained: it embeds the shared
``colornames`` module verbatim (so it has no runtime import dependency
on the separately-installed palette bundle) followed by a small toggle tail.

Because the scripts are generated, the color-key map, the colorNames.txt
filename, the parsing, and the layer-color derivation can never drift from the
palette again — they all come from the one canonical module.

Run from the repo root:

    uv run python tools/generate_shortcuts.py
"""

from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CANONICAL_MODULE = (
    REPO / "Color Flow.glyphsPalette" / "Contents" / "Resources" / "colornames.py"
)
NAV_MODULE = (
    REPO / "Color Flow.glyphsPalette" / "Contents" / "Resources" / "colornav.py"
)
SHORTCUT_DIR = REPO / "Color Flow Shortcut"

# index -> display name used in the filename and the #MenuTitle. These display
# spellings (Green/Blue/Grey rather than lightGreen/lightBlue/lightGray) match
# the original files so existing user keyboard bindings keep working.
DISPLAY_NAMES = [
    (0, "Red"),
    (1, "Orange"),
    (2, "Brown"),
    (3, "Yellow"),
    (4, "Green"),
    (5, "DarkGreen"),
    (6, "Blue"),
    (7, "DarkBlue"),
    (8, "Purple"),
    (9, "Magenta"),
    (10, "Grey"),
    (11, "Charcoal"),
]

HEADER = """#MenuTitle: Toggle {display} Checkbox (Color Flow)
# =============================================================================
# AUTO-GENERATED by tools/generate_shortcuts.py — DO NOT EDIT BY HAND.
# Regenerate after editing the template or colornames.py:
#     uv run python tools/generate_shortcuts.py
#
# Toggles Color Flow step "{index}" on the selected layers: flips the per-layer
# checkbox, updates the per-master progress count (keyed by master.id, matching
# the palette), and recomputes the native layer color.
# =============================================================================

"""

TOGGLE_TAIL = '''

# ---------------------------------------------------------------------------
# Toggle logic (auto-generated tail)
# ---------------------------------------------------------------------------

_COLOR_CHECK = "__COLOR_INDEX__"
_COUNTS_KEY = "com.hugojourdan.ColorFlow-counts-"


def _color_flow_font_dir(font):
    return os.path.dirname(font.filepath) if font.filepath else None


def _color_flow_toggle():
    font = Glyphs.font
    if font is None:
        return
    master = font.selectedFontMaster
    layers = font.selectedLayers
    if master is None or not layers:
        return
    meaning = load_meaning(_color_flow_font_dir(font))
    order = list(meaning.keys())
    if _COLOR_CHECK not in meaning:
        return  # this color is hidden in the current colorNames.txt
    free = bool(Glyphs.defaults["com.hugojourdan.ColorFlow-FreeMode"])
    target = int(_COLOR_CHECK)
    for layer in layers:
        if free:
            # single-select: toggle this colour exclusively (clear if re-pressed)
            layer.color = None if layer.color == target else target
        else:
            # contiguous steps: derive from layer.color, nothing saved in the file
            state = checked_state_for_color(layer.color, order)
            state[_COLOR_CHECK] = not state.get(_COLOR_CHECK, False)
            layer.color = layer_color_for_state(state, order)
    # Invalidate the palette's cached counts (volatile tempData).
    font.tempData[_COUNTS_KEY + master.id] = None


_color_flow_toggle()
'''

JUMP_HEADER = """#MenuTitle: Jump To Next Unfinished (Color Flow)
# =============================================================================
# AUTO-GENERATED by tools/generate_shortcuts.py — DO NOT EDIT BY HAND.
# Regenerate after editing the template or colornames.py / colornav.py:
#     uv run python tools/generate_shortcuts.py
#
# Opens the next glyph whose current-master layer.color is not the final visible
# workflow step (see colorNames.txt). Scans the font in order from the active
# glyph, wraps around, and opens the result in the Edit view. Recipes are ignored
# in v1 — it uses the single global final step.
#
# v1 always opens a new tab; reusing an already-open Edit tab (moving the cursor
# to the target glyph within it) is deferred.
# =============================================================================

"""

JUMP_TAIL = '''

# ---------------------------------------------------------------------------
# Navigation logic (auto-generated tail)
# ---------------------------------------------------------------------------


def _color_flow_jump_font_dir(font):
    return os.path.dirname(font.filepath) if font.filepath else None


def _color_flow_current_position(font, names):
    # Index of the active glyph in the font-order name list, or -1 if unknown.
    try:
        layers = font.selectedLayers
    except Exception:
        layers = None
    if layers:
        parent = layers[0].parent
        current = parent.name if parent is not None else None
        if current in names:
            return names.index(current)
    return -1


def _color_flow_jump():
    font = Glyphs.font
    if font is None:
        Message("Open a font first.", title="Color Flow")
        return
    master = font.selectedFontMaster
    if master is None:
        return
    meaning = load_meaning(_color_flow_jump_font_dir(font))
    final_step = final_visible_step(meaning)
    master_id = master.id
    pairs = []
    for glyph in font.glyphs:
        layer = glyph.layers[master_id]
        color = layer.color if layer is not None else None
        pairs.append((glyph.name, color))
    names = [name for name, _color in pairs]
    position = _color_flow_current_position(font, names)
    index = next_unfinished_index(pairs, final_step, position)
    if index is None:
        Message("All glyphs finished.", title="Color Flow")
        return
    font.newTab("/" + names[index])


_color_flow_jump()
'''


def build_script(index: int, display: str, module_source: str) -> str:
    """Assemble one shortcut script: header + embedded module + toggle tail."""
    header = HEADER.format(display=display, index=index)
    # The tail contains literal { } (dict comprehensions), so substitute the
    # index with a plain token rather than str.format.
    tail = TOGGLE_TAIL.replace("__COLOR_INDEX__", str(index))
    return header + module_source + tail


def build_jump_script(module_source: str, nav_source: str) -> str:
    """Assemble the jump shortcut: header + colornames + colornav + nav tail.

    ``colornames`` already supplies the single ``from __future__ import
    annotations`` at the top of the concatenated script, so the duplicate one
    inside the embedded ``colornav`` source is dropped — a future import is only
    valid at the start of a module and would otherwise raise SyntaxError.
    """
    nav_embedded = nav_source.replace(
        "from __future__ import annotations\n", "", 1
    )
    return JUMP_HEADER + module_source + "\n" + nav_embedded + JUMP_TAIL


def main() -> None:
    module_source = CANONICAL_MODULE.read_text(encoding="utf-8")
    nav_source = NAV_MODULE.read_text(encoding="utf-8")
    SHORTCUT_DIR.mkdir(parents=True, exist_ok=True)
    for index, display in DISPLAY_NAMES:
        script = build_script(index, display, module_source)
        out_path = SHORTCUT_DIR / f"Toggle {display} CheckBox (Color Flow).py"
        out_path.write_text(script, encoding="utf-8")
        print(f"wrote {out_path.name}")
    jump = build_jump_script(module_source, nav_source)
    jump_path = SHORTCUT_DIR / "Jump To Next Unfinished (Color Flow).py"
    jump_path.write_text(jump, encoding="utf-8")
    print(f"wrote {jump_path.name}")
    print(f"\nGenerated {len(DISPLAY_NAMES)} toggle scripts + 1 jump script in {SHORTCUT_DIR}")


if __name__ == "__main__":
    main()

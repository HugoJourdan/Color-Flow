#!/usr/bin/env python3
"""Generate the 12 "Toggle <Color> Checkbox (Color Flow)" shortcut scripts.

Each emitted script is self-contained: it embeds the shared
``colornames`` module verbatim (so it has no runtime import dependency
on the separately-installed palette bundle) followed by a small toggle tail.

Because the scripts are generated, the color-key map, the colorNames.txt
filename, the parsing, and the layer-color derivation can never drift from the
palette again — they all come from the one canonical module.

Run from the repo root:

    uv run python tools/generate_shortcuts.py
"""

from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CANONICAL_MODULE = (
    REPO / "Color Flow.glyphsPalette" / "Contents" / "Resources" / "colornames.py"
)
SHORTCUT_DIR = REPO / "Color Flow Shortcut"

# index -> display name used in the filename and the #MenuTitle. These display
# spellings (Green/Blue/Grey rather than lightGreen/lightBlue/lightGray) match
# the original files so existing user keyboard bindings keep working.
DISPLAY_NAMES = [
    (0, "Red"),
    (1, "Orange"),
    (2, "Brown"),
    (3, "Yellow"),
    (4, "Green"),
    (5, "DarkGreen"),
    (6, "Blue"),
    (7, "DarkBlue"),
    (8, "Purple"),
    (9, "Magenta"),
    (10, "Grey"),
    (11, "Charcoal"),
]

HEADER = """#MenuTitle: Toggle {display} Checkbox (Color Flow)
# -*- coding: utf-8 -*-
# =============================================================================
# AUTO-GENERATED by tools/generate_shortcuts.py — DO NOT EDIT BY HAND.
# Regenerate after editing the template or colornames.py:
#     uv run python tools/generate_shortcuts.py
#
# Toggles Color Flow step "{index}" on the selected layers: flips the per-layer
# checkbox, updates the per-master progress count (keyed by master.id, matching
# the palette), and recomputes the native layer color.
# =============================================================================

"""

TOGGLE_TAIL = '''

# ---------------------------------------------------------------------------
# Toggle logic (auto-generated tail)
# ---------------------------------------------------------------------------

_COLOR_CHECK = "__COLOR_INDEX__"
_COUNTS_KEY = "com.hugojourdan.ColorFlow-counts-"


def _color_flow_font_dir(font):
    return os.path.dirname(font.filepath) if font.filepath else None


def _color_flow_toggle():
    font = Glyphs.font
    if font is None:
        return
    master = font.selectedFontMaster
    layers = font.selectedLayers
    if master is None or not layers:
        return
    meaning = load_meaning(_color_flow_font_dir(font))
    order = list(meaning.keys())
    if _COLOR_CHECK not in meaning:
        return  # this color is hidden in the current colorNames.txt
    _LAYER_KEY = "com.hugojourdan.ColorFlow"
    free = bool(Glyphs.defaults["com.hugojourdan.ColorFlow-FreeMode"])
    for layer in layers:
        if free:
            # Independent steps: state lives in userData; layer.color = highest.
            stored = layer.userData[_LAYER_KEY]
            if stored:
                state = {i: bool(i in stored and stored[i]) for i in order}
            else:
                state = checked_state_for_color(layer.color, order)
            state[_COLOR_CHECK] = not state.get(_COLOR_CHECK, False)
            layer.userData[_LAYER_KEY] = {i: bool(state.get(i, False)) for i in order}
            layer.color = highest_checked(state, order)
        else:
            # Contiguous steps: derive from layer.color, nothing saved in the file.
            state = checked_state_for_color(layer.color, order)
            state[_COLOR_CHECK] = not state.get(_COLOR_CHECK, False)
            layer.color = layer_color_for_state(state, order)
    # Invalidate the palette's cached counts (volatile tempData).
    font.tempData[_COUNTS_KEY + master.id] = None


_color_flow_toggle()
'''


def build_script(index: int, display: str, module_source: str) -> str:
    """Assemble one shortcut script: header + embedded module + toggle tail."""
    header = HEADER.format(display=display, index=index)
    # The tail contains literal { } (dict comprehensions), so substitute the
    # index with a plain token rather than str.format.
    tail = TOGGLE_TAIL.replace("__COLOR_INDEX__", str(index))
    return header + module_source + tail


def main() -> None:
    module_source = CANONICAL_MODULE.read_text(encoding="utf-8")
    SHORTCUT_DIR.mkdir(parents=True, exist_ok=True)
    for index, display in DISPLAY_NAMES:
        script = build_script(index, display, module_source)
        out_path = SHORTCUT_DIR / f"Toggle {display} CheckBox (Color Flow).py"
        out_path.write_text(script, encoding="utf-8")
        print(f"wrote {out_path.name}")
    print(f"\nGenerated {len(DISPLAY_NAMES)} shortcut scripts in {SHORTCUT_DIR}")


if __name__ == "__main__":
    main()
